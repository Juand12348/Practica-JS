// Ciclo While

console.log("*** Ciclo while ***");
let numero = 0;

while(numero < 10){
    numero++;
    console.log(numero);
}

console.log("*** Ciclo Do While ***");
numero = 0;

do{
    numero++;
    console.log(numero);
}while(numero < 10);

// Ciclo For
console.log("*** Ciclo For ***");
for(let n = 1; n < 11; n++){
    console.log(n);
}